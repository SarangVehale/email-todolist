#!/usr/bin/env python3
"""Regenerates the automated section of docs/TESTCASES.md from the real test files.

Every `#[test]` function in engine/tests/*.rs becomes one catalogue row: its file (area), name, and the leading
doc/comment line if any. Every `it("...")` in app/test/*.test.mjs (the window, run in a real browser) becomes a row too.
Run from the repository root:  python scripts/gen_testcases.py
The hand-written manual test plan stays in docs/TESTCASES.manual.md and is appended unchanged.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
AREAS = {
    "engine.rs": "Parsing, signals, rules, store basics",
    "core.rs": "Settings, model replies, store actions, reset",
    "security.rs": "Security: injection, MIME depth, sender trust",
    "security_more.rs": "Security: write-back targeting, settings validation, prompts, retention",
    "review_fixes.rs": "Security: second review (reply address, preferences, phone limits, retention)",
    "hub.rs": "Phone hub: headers, rate limit, limits, stalls, tokens, static files",
    "hub_edge.rs": "Phone hub: odd HTTP, auth headers, floods",
    "features.rs": "Drafts, snooze, preferences, scheduling, commands",
    "edge_cases.rs": "Edge cases: odd mail, HTML-only, model output, settings, dates, store, drafts",
    "imap_flows.rs": "IMAP protocol: sync, write-back, drafts, fallbacks, retries (mock server)",
    "signin.rs": "Sign in with Google and Microsoft (scripted token and mail servers)",
    "phase12.rs": "Phase 12: the pages the app opens in the browser",
    "core.rs": "Inside the engine: the core's status and state (tests that need what is private to it)",
}


def tests_in(path: pathlib.Path):
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"\s*fn (\w+)\(", line)
        if not m or i == 0 or "#[test]" not in "\n".join(lines[max(0, i - 3):i]):
            continue
        note = ""
        j = i - 1
        while j >= 0 and (lines[j].strip().startswith(("#[", "//")) or not lines[j].strip()):
            if lines[j].strip().startswith("//"):
                note = lines[j].strip().lstrip("/ ").strip()
            j -= 1
            if i - j > 6:
                break
        yield m.group(1), note


WINDOW_AREAS = {
    "list.test.mjs": "Window: the long list (150 rows at a time, Show more, Show all)",
    "cursor.test.mjs": "Window: the cursor, folds, finishing, undo, select mode, the Done tab",
    "mailboxes.test.mjs": "Window: several mailboxes (the Add dialog, Settings, tags and chips)",
    "restore.test.mjs": "Window: the Backup section and the restore dialog",
    "easy-setup.test.mjs": "Window: the first-run screens (the address, a code, sentences for errors)",
    "easy-look.test.mjs": "Window: the simple view (Done and Later, plain headings, text size, light colours)",
    "signin.test.mjs": "Window: sign in with Google and Microsoft",
}


def window_tests_in(path: pathlib.Path):
    """(suite, title) for each it("...") of a window test file."""
    suite = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r'\s*suite\("(.+?)", ', line)
        if m:
            suite = m.group(1)
        m = re.match(r'\s*it\("(.+?)", async ', line)
        if m:
            yield suite, m.group(1)


def main():
    out = ["# Automated test catalogue", "",
           "_Generated by `scripts/gen_testcases.py` from `engine/tests/*.rs` and `app/test/*.test.mjs`. Do not edit by hand._", ""]
    total = 0
    # the tests folder, and any test that has to sit inside a source file because it needs what is private there
    engine_files = sorted((ROOT / "engine" / "tests").glob("*.rs")) + sorted((ROOT / "engine" / "src").glob("*.rs"))
    engine_with_tests = 0
    for f in engine_files:
        rows = list(tests_in(f))
        if not rows:
            continue
        total += len(rows)
        engine_with_tests += 1
        out += [f"## {AREAS.get(f.name, f.name)}", f"`engine/{f.parent.name}/{f.name}` — {len(rows)} tests", "",
                "| Test | What it proves |", "| --- | --- |"]
        for name, note in rows:
            out.append(f"| `{name}` | {name.replace('_', ' ')}{(' — ' + note) if note else ''} |")
        out.append("")
    window_total = 0
    window_files = sorted((ROOT / "app" / "test").glob("*.test.mjs"))
    for f in window_files:
        rows = list(window_tests_in(f))
        if not rows:
            continue
        window_total += len(rows)
        out += [f"## {WINDOW_AREAS.get(f.name, f.name)}", f"`app/test/{f.name}` — {len(rows)} tests", "",
                "| Group | What it proves |", "| --- | --- |"]
        for suite_name, title in rows:
            out.append(f"| {suite_name} | {title.replace('|', '/')} |")
        out.append("")
    out.insert(3, f"**{total} automated tests** across {engine_with_tests} files. "
                  "Run them with `cd engine && cargo test`.")
    out.insert(4, "")
    out.insert(5, f"**{window_total} window tests** across {len(window_files)} files, run against the real window in a real browser. "
                  "Run them with `cd app && npm test`.")
    manual = ROOT / "docs" / "TESTCASES.manual.md"
    text = "\n".join(out) + "\n"
    if manual.exists():
        text += "\n" + manual.read_text(encoding="utf-8")
    (ROOT / "docs" / "TESTCASES.md").write_text(text, encoding="utf-8")
    print(f"wrote docs/TESTCASES.md ({total} engine tests, {window_total} window tests)")


if __name__ == "__main__":
    sys.exit(main())
